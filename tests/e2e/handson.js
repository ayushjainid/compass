// The hands-on tour: optional, one lit-up control at a time, you do each thing yourself, and it's a practice run —
// setup, settings, this week and the tasks it made are all put back at the end.
const { chromium } = require('./engine');
const { newCtx, newPage, report, launch, W, touch } = require('./harness');
const R = []; const ok = (n, c, i) => R.push({ n, pass: !!c, i: c ? undefined : i });
const SHOTS = process.env.SHOTS;
(async () => { const b = await launch(chromium);
  const ctx = await newCtx(b), A = await newPage(ctx), { p, tap, store, text, errs } = A;
  const settle = (ms = 400) => p.waitForTimeout(ms);
  const shot = async n => { if (SHOTS) await p.screenshot({ path: `${SHOTS}/${n}.png` }); };
  const t = new Date(); t.setHours(11, 0, 0, 0); await p.clock.setFixedTime(t);
  await p.goto('http://compass.test/'); await settle(500);
  await tap('.lhero [data-act=signin]'); await settle(600);
  await tap('[data-act=obNext]'); for (const v of ['rel', 'body', 'learn']) await tap(`[data-act=obValue][data-v=${v}]`);
  while (await p.locator('[data-act=obNext]').count()) await tap('[data-act=obNext]');
  await settle(1500);
  const before = await store(); const snap = k => JSON.stringify(Object.assign({}, before[k], { _w: 0 }));
  const items0 = Object.keys(before).filter(k => /^lists\/.*\/items\//.test(k)).length;
  ok('after setup: the first card offers a 2-minute tour', await p.locator('.tip [data-act=htStart]').count() === 1);
  await tap('.tip [data-act=htStart]'); await settle(500);
  const coach = () => text('#htCoach');
  const lit = () => p.evaluate(() => { const s = document.getElementById('htSpot'); if (!s || s.hidden) return null; const r = s.getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2, full: s.classList.contains('full') }; });
  /* the light follows a scroll or a sheet sliding in, so give it a moment to settle on the control */
  let lastLit = null;
  const litOnce = async sel => { const l = await lit(); if (!l || l.full) { lastLit = { l }; return false; } const r = await p.locator(sel).first().boundingBox().catch(() => null); lastLit = { l, r }; return !!r && l.x >= r.x - 2 && l.x <= r.x + r.width + 2 && l.y >= r.y - 2 && l.y <= r.y + r.height + 2; };
  const litOn = async sel => { for (let i = 0; i < 12; i++) { if (await litOnce(sel)) return true; await settle(250); } console.log('lit miss', sel, JSON.stringify(lastLit)); return false; };
  ok('it says up front that it is a practice run', /practice run/i.test(await coach()) && /cleared at the end/.test(await coach()));
  await shot('0-start');
  await tap('#htCoach [data-act=htNext]'); await settle(600);
  ok('step 1: tick a floor, with the floor lit up', /Tick a floor/.test(await coach()) && /1 of 7/.test(await coach()) && await litOn('#main .dayrow[data-act=anchor]'), await coach());
  await shot('1-tick');
  /* tapping somewhere else doesn't move it on */
  await settle(300);
  const k = await p.evaluate(() => { const s = document.getElementById('htSpot').getBoundingClientRect(); const el = document.elementsFromPoint(s.left + s.width / 2, s.top + s.height / 2).find(e => e.matches && e.matches('.dayrow')); return el && el.dataset.k; });
  await tap(`#main .dayrow[data-k="${k}"]`); await settle(1200);
  ok('doing it moves the tour on: add a task', /Add a task the way you'd say it/.test(await coach()) && await litOn('.qadd'), [await coach(), lastLit]);
  await shot('2-type');
  await tap('#htCoach [data-act=htType]'); await settle(300);
  ok('"Type it for me" fills the box', await p.locator('#qAdd').inputValue() === 'call mum fri 6pm');
  await p.keyboard.press('Enter'); await settle(1300);
  ok('adding it moves on: finish it or move it, with the new task lit', /Finish it or move it/.test(await coach()) && await litOn('.lrow:has-text("call mum")'), await coach());
  await shot('3-swipe');
  await tap('.lrow:has-text("call mum") .tick'); await settle(1500);
  ok('finishing it moves on: close the day, with a card lit', /Close the day/.test(await coach()) && await p.locator('.cksheet #ckCard').count() === 1 && await litOn('#ckCard'), await coach());
  await shot('4-close');
  await p.locator('.ck [data-act=ckYes]').click(); await settle(1500);
  ok('answering a card moves on: anything for tomorrow', /anything for tomorrow/i.test(await coach()) && /Anything for tomorrow/.test(await text('.ck h2')) && await litOn('.ck [data-act=ckFinish]'), [await coach(), lastLit]);
  await shot('5-tomorrow');
  await p.locator('.ck [data-act=ckFinish]').click(); await settle(1500);
  ok('Done moves on: a floor that counts by default, its switch lit', /count by default/.test(await coach()) && await litOn('.sheet [data-act=cToggle][data-f=dflt]'), await coach());
  await shot('6-dflt');
  await p.locator('.sheet [data-act=cToggle][data-f=dflt]').click(); await settle(1500);
  ok('flipping it moves on (without saving): the Sunday review, its tab lit', /Sunday/.test(await coach()) && await p.locator('.sheet').count() === 0 && await litOn('#tabs [data-act=tab][data-t=review]'), await coach());
  await shot('7-review');
  await tap('#tabs [data-act=tab][data-t=review]'); await settle(1500);
  ok('the end says what the loop is', /That's the whole loop/.test(await coach()) && /Finish/.test(await coach()));
  await shot('8-end');
  await tap('#htCoach [data-act=htNext]'); await settle(2000);
  const after = await store();
  ok('finishing clears it all: no coach, no light', await p.locator('#htCoach, #htSpot').count() === 0 && /Tour done/.test(await text('.toast')));
  ok('…the task it made is gone', Object.keys(after).filter(k => /^lists\/.*\/items\//.test(k)).length === items0);
  ok('…setup is as it was (the switch never saved)', !((after['users/u1/docs/profile'] || {}).components || []).some(c => c.dflt));
  const wk = Object.keys(after).find(k => /users\/u1\/docs\/w-/.test(k)), wkd = after[wk] || {};
  ok('…and this week has no ticks or answers from the practice run', !Object.values(wkd.days || {}).some(d => Object.values(d.a || {}).some(Boolean) || d.ck || d.ckAt), wkd.days);
  /* again, from Compass, and ending early */
  await tap('[data-act=tab][data-t=compass]'); await tap('[data-act=cSec][data-k=app]');
  await tap('#csec-app [data-act=htStart]'); await settle(500);
  ok('Compass → Settings → Hands-on tour starts it again', /practice run/i.test(await coach()));
  await tap('#htCoach [data-act=htNext]'); await settle(500);
  await tap('#htCoach [data-act=htNext]'); await settle(500);
  ok('"Skip this step" skips', /Add a task/.test(await coach()));
  await tap('#htCoach [data-act=htEnd]'); await settle(800);
  ok('"End tour" ends it anywhere', await p.locator('#htCoach').count() === 0);
  ok('no save errors along the way', !(await p.locator('#banner:not([hidden])').count()), await p.locator('#banner').innerText().catch(() => ''));
  ok('no page errors', !errs.length, errs);
  report(`handson ${W}`, R);
  await b.close();
})().catch(e => { console.log('CRASH', e.message.split('\n').slice(0, 4).join(' | ')); report('handson', R); process.exit(1); });
